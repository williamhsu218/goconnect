#!/usr/bin/env python3
"""Single release source; generated language constants are checked before builds."""
import argparse
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parent.parent

def load_version():
    value = json.loads((ROOT / "VERSION.json").read_text())
    for field, pattern in {"version": r"\d+\.\d+\.\d+", "build": r"[1-9]\d*", "deploymentTarget": r"\d+\.\d+"}.items():
        if not isinstance(value.get(field), str) or not re.fullmatch(pattern, value[field]):
            raise ValueError(f"Invalid VERSION.json field: {field}")
    return value

def generated_sources(value):
    return {
        ROOT / "Sources/GoConnectCore/BuildVersion.swift": (
            '// Generated by script/version.py from VERSION.json. Do not edit.\n'
            'extension Product {\n'
            f'    public static let version = "{value["version"]}"\n'
            f'    public static let build = "{value["build"]}"\n'
            '}\n'),
        ROOT / "Transport/cmd/goconnect-transport/build_version.go": (
            '// Code generated by script/version.py from VERSION.json; DO NOT EDIT.\n'
            'package main\n\n'
            f'const transportVersion = "{value["version"]}"\n'),
    }

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--generate', action='store_true')
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--field', choices=['version', 'build', 'deploymentTarget'])
    args = parser.parse_args()
    value = load_version()
    if args.field:
        print(value[args.field])
        return
    for path, text in generated_sources(value).items():
        if args.generate:
            path.write_text(text)
        elif not path.exists() or path.read_text() != text:
            raise SystemExit('Stale version constants; run python3 script/version.py --generate')
    print('Version constants match VERSION.json.')

if __name__ == '__main__':
    main()
